"""Bridge to Inspect (inspect_ai), the task format METR and UK AISI use.

`export` converts an evalh task spec into the two artifacts an Inspect
pipeline consumes:

  dataset.jsonl   — {"input", "target", "metadata"} per sample; metadata
                    carries the evalh grader so scoring semantics travel
                    with the data
  <name>_task.py  — a loadable @task whose scorer calls evalh's
                    deterministic `grade`, so results are comparable
                    across both harnesses

Not an Inspect shim: this emits real Inspect artifacts, runnable with
`inspect eval <name>_task.py` once inspect_ai is installed. evalh itself
stays stdlib-only.
"""

from __future__ import annotations

import json
import os
import re

TASK_TEMPLATE = '''"""Generated by evalh inspect-export — do not edit by hand.

Run: inspect eval {task_module} --model <provider/model>
Requires: pip install inspect_ai  (and evalh importable for scoring)
"""

from inspect_ai import Task, task
from inspect_ai.dataset import json_dataset
from inspect_ai.scorer import Score, Target, accuracy, scorer, stderr
from inspect_ai.solver import generate


@scorer(metrics=[accuracy(), stderr()])
def evalh_grade():
    """evalh deterministic grader wrapped as an Inspect scorer."""
    async def score(state, target: Target):
        from evalh.graders import grade
        g = grade(state.output.completion, state.metadata["grader"])
        return Score(
            value="C" if g["score"] else "I",
            answer=state.output.completion,
            explanation=g["label"])
    return score


@task
def {task_name}():
    return Task(
        dataset=json_dataset("dataset.jsonl"),
        solver=[generate()],
        scorer=evalh_grade(),
    )
'''


def _task_name(spec_path: str) -> str:
    base = os.path.splitext(os.path.basename(spec_path))[0]
    return re.sub(r"\W+", "_", base).strip("_").lower() or "evalh_task"


def export(spec_path: str, out_dir: str) -> dict:
    """Convert an evalh spec into dataset.jsonl + <name>_task.py."""
    from .tasks import load_tasks
    tasks = load_tasks(spec_path)
    os.makedirs(out_dir, exist_ok=True)

    ds_path = os.path.join(out_dir, "dataset.jsonl")
    with open(ds_path, "w", encoding="utf-8") as f:
        for t in tasks:
            f.write(json.dumps({
                "input": t["prompt"],
                "target": t["grader"].get("value", ""),
                "metadata": {"id": t["id"], "tag": t["tag"],
                             "grader": t["grader"]},
            }, ensure_ascii=False) + "\n")

    name = _task_name(spec_path)
    task_path = os.path.join(out_dir, f"{name}_task.py")
    with open(task_path, "w", encoding="utf-8") as f:
        f.write(TASK_TEMPLATE.format(task_name=name,
                                     task_module=f"{name}_task.py"))
    return {"dataset": ds_path, "task_module": task_path,
            "n_tasks": len(tasks)}
